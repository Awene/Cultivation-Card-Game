function section(prefix) {
  const m = [...source.matchAll(/^## (.+)$/gm)].find((m) =>
    m[1].startsWith(prefix),
  );
  assert(m, prefix);
  return source
    .slice(m.index + m[0].length)
    .split(/^## /m)[0]
    .trim();
}
function blocks(s, level) {
  const ms = [...s.matchAll(new RegExp("^#{" + level + "} (.+)$", "gm"))];
  return ms.map((m, i) => ({
    title: m[1],
    body: s
      .slice(m.index + m[0].length, ms[i + 1]?.index ?? s.length)
      .split(new RegExp("^#{1," + (level - 1) + "} ", "m"))[0]
      .trim(),
  }));
}
